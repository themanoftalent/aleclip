import Foundation
import AppKit
import CryptoKit

@MainActor
public final class ClipboardMonitor: ObservableObject {
    public static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount: Int = -1
    public var isInternalCopy: Bool = false

    // Concealed / Transient types used by password managers and private generators
    private let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.dstoecker.xclipboard")
    ]

    private init() {}

    public func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkForChanges()
            }
        }
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func checkForChanges() {
        let pasteboard = NSPasteboard.general
        let currentChangeCount = pasteboard.changeCount

        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        // If this copy was initiated by AleClip itself, skip recording
        if isInternalCopy {
            isInternalCopy = false
            return
        }

        processPasteboard(pasteboard)
    }

    private func processPasteboard(_ pasteboard: NSPasteboard) {
        let types = pasteboard.types ?? []

        // 1. Skip concealed and transient pasteboard types (passwords, sensitive data)
        for concealed in concealedTypes {
            if types.contains(concealed) {
                return
            }
        }

        // 2. Check excluded apps
        let frontmostApp = NSWorkspace.shared.frontmostApplication
        let bundleId = frontmostApp?.bundleIdentifier
        let appName = frontmostApp?.localizedName

        if let bundleId = bundleId,
           StorageService.shared.settings.excludedBundleIds.contains(bundleId) {
            return
        }

        // 3. Extract clip according to type priority
        if let clip = extractClip(from: pasteboard, bundleId: bundleId, appName: appName) {
            StorageService.shared.addClip(clip)
        }
    }

    private func extractClip(from pasteboard: NSPasteboard, bundleId: String?, appName: String?) -> ClipItem? {
        // Priority A: Color
        if pasteboard.types?.contains(.color) == true,
           let color = NSColor(from: pasteboard) {
            let hex = colorToHex(color)
            let hash = hashString("color:\(hex)")
            return ClipItem(
                type: .color,
                plainText: hex,
                colorHex: hex,
                sourceAppBundleId: bundleId,
                sourceAppName: appName,
                contentHash: hash
            )
        }

        // Priority B: File URL
        if let fileURLs = pasteboard.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true
        ]) as? [URL], let firstURL = fileURLs.first {
            let path = firstURL.path
            let hash = hashString("file:\(path)")
            return ClipItem(
                type: .file,
                plainText: path,
                url: firstURL.absoluteString,
                sourceAppBundleId: bundleId,
                sourceAppName: appName,
                contentHash: hash
            )
        }

        // Priority C: Image (PNG / TIFF)
        if pasteboard.types?.contains(.png) == true || pasteboard.types?.contains(.tiff) == true {
            var imageData: Data?
            if let pngData = pasteboard.data(forType: .png) {
                imageData = pngData
            } else if let tiffData = pasteboard.data(forType: .tiff),
                      let rep = NSBitmapImageRep(data: tiffData),
                      let png = rep.representation(using: .png, properties: [:]) {
                imageData = png
            }

            if let data = imageData, !data.isEmpty {
                let hash = hashData(data)
                if let savedFilename = StorageService.shared.saveImageBlob(data) {
                    return ClipItem(
                        type: .image,
                        plainText: "[Image]",
                        imageFileName: savedFilename,
                        sourceAppBundleId: bundleId,
                        sourceAppName: appName,
                        contentHash: hash
                    )
                }
            }
        }

        // Priority D: Web URL
        if let url = pasteboard.string(forType: .URL),
           let parsedURL = URL(string: url),
           parsedURL.scheme == "http" || parsedURL.scheme == "https" {
            let hash = hashString("url:\(url)")
            return ClipItem(
                type: .link,
                plainText: url,
                url: url,
                sourceAppBundleId: bundleId,
                sourceAppName: appName,
                contentHash: hash
            )
        }

        // Priority E: HTML Content
        if let html = pasteboard.string(forType: .html), !html.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let plainText = pasteboard.string(forType: .string) ?? html
            let hash = hashString("html:\(plainText)")
            return ClipItem(
                type: .html,
                plainText: plainText,
                htmlContent: html,
                sourceAppBundleId: bundleId,
                sourceAppName: appName,
                contentHash: hash
            )
        }

        // Priority F: Rich Text (RTF)
        if let rtfData = pasteboard.data(forType: .rtf) {
            let plainText = pasteboard.string(forType: .string) ?? "[Rich Text]"
            let hash = hashData(rtfData)
            return ClipItem(
                type: .richText,
                plainText: plainText,
                rtfData: rtfData,
                sourceAppBundleId: bundleId,
                sourceAppName: appName,
                contentHash: hash
            )
        }

        // Priority G: Plain Text
        if let string = pasteboard.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }

            // Check if string is actually a URL
            if (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://")),
               let _ = URL(string: trimmed) {
                let hash = hashString("url:\(trimmed)")
                return ClipItem(
                    type: .link,
                    plainText: trimmed,
                    url: trimmed,
                    sourceAppBundleId: bundleId,
                    sourceAppName: appName,
                    contentHash: hash
                )
            }

            let hash = hashString("text:\(string)")
            return ClipItem(
                type: .text,
                plainText: string,
                sourceAppBundleId: bundleId,
                sourceAppName: appName,
                contentHash: hash
            )
        }

        return nil
    }

    private func colorToHex(_ color: NSColor) -> String {
        guard let rgbColor = color.usingColorSpace(.sRGB) else { return "#000000" }
        let r = Int(round(rgbColor.redComponent * 255.0))
        let g = Int(round(rgbColor.greenComponent * 255.0))
        let b = Int(round(rgbColor.blueComponent * 255.0))
        return String(format: "#%02X%02X%02X", r, g, b)
    }

    private func hashString(_ string: String) -> String {
        let inputData = Data(string.utf8)
        let hashed = SHA256.hash(data: inputData)
        return hashed.compactMap { String(format: "%02x", $0) }.joined()
    }

    private func hashData(_ data: Data) -> String {
        let hashed = SHA256.hash(data: data)
        return hashed.compactMap { String(format: "%02x", $0) }.joined()
    }
}
